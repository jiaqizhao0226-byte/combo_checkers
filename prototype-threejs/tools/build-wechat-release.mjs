import { createHash } from 'node:crypto';
import {
  copyFile, mkdir, readFile, readdir, rm, stat, writeFile,
} from 'node:fs/promises';
import { basename, dirname, extname, join, relative, resolve, sep } from 'node:path';

function locateSourceRoot(startPath) {
  let current = resolve(startPath || process.cwd());
  if (!current.endsWith('.mjs') && !current.endsWith('.js')) current = resolve(current, 'prototype-threejs');
  else current = dirname(current);
  for (let depth = 0; depth < 5; depth += 1) {
    if (basename(current) === 'prototype-threejs') return current;
    current = dirname(current);
  }
  return resolve(process.cwd(), 'prototype-threejs');
}

const sourceRoot = locateSourceRoot(process.argv[1]);
const toolsRoot = resolve(sourceRoot, 'tools');
const repositoryRoot = resolve(sourceRoot, '..');
const distRoot = resolve(repositoryRoot, 'dist');
const defaultOutput = resolve(distRoot, 'wechat-release');

function manifestPathFor(outputRoot) {
  return resolve(dirname(outputRoot), `${basename(outputRoot)}.manifest.json`);
}

export const RELEASE_LIMITS = Object.freeze({
  mainPackageBytes: 4 * 1024 * 1024,
  totalPackageBytes: 20 * 1024 * 1024,
});

const AUDIO_LAYOUT = Object.freeze({
  'audio-menu': [
    'bgm_menu.ogg',
    'sfx/ui_click.ogg',
    'sfx/sfx_hero_jump.ogg',
    'sfx/sfx_attack_hit.ogg',
    'sfx/sfx_enemy_death.ogg',
    'sfx/sfx_victory.ogg',
    'sfx/sfx_defeat.ogg',
  ],
  'audio-battle': [
    'bgm_battle_calm.ogg',
    'bgm_battle.ogg',
    'bgm_boss_abyss.ogg',
  ],
});

const RELEASE_PROFILE_SOURCE = `// Generated by tools/build-wechat-release.mjs. Do not edit this staged file.\nexport const WECHAT_BUILD_PROFILE = Object.freeze({\n  name: 'release',\n  release: true,\n  bgmPaths: Object.freeze({\n    menu: 'packages/audio-menu/bgm_menu.ogg',\n    battle_calm: 'packages/audio-battle/bgm_battle_calm.ogg',\n    battle: 'packages/audio-battle/bgm_battle.ogg',\n    boss_abyss: 'packages/audio-battle/bgm_boss_abyss.ogg',\n  }),\n  sfxPaths: Object.freeze({\n    ui_click: 'packages/audio-menu/sfx/ui_click.ogg',\n    hero_jump: 'packages/audio-menu/sfx/sfx_hero_jump.ogg',\n    attack_hit: 'packages/audio-menu/sfx/sfx_attack_hit.ogg',\n    enemy_death: 'packages/audio-menu/sfx/sfx_enemy_death.ogg',\n    victory: 'packages/audio-menu/sfx/sfx_victory.ogg',\n    defeat: 'packages/audio-menu/sfx/sfx_defeat.ogg',\n  }),\n  bgmPackages: Object.freeze({\n    menu: 'audio-menu',\n    battle_calm: 'audio-battle',\n    battle: 'audio-battle',\n    boss_abyss: 'audio-battle',\n  }),\n  sfxPackages: Object.freeze({\n    ui_click: 'audio-menu',\n    hero_jump: 'audio-menu',\n    attack_hit: 'audio-menu',\n    enemy_death: 'audio-menu',\n    victory: 'audio-menu',\n    defeat: 'audio-menu',\n  }),\n});\n`;

function assertSafeOutput(outputRoot) {
  const rel = relative(distRoot, outputRoot);
  if (!rel || rel === '.' || rel.startsWith(`..${sep}`) || rel === '..') {
    throw new Error(`Release output must be a child of ${distRoot}`);
  }
}

function relativeImportSpecifiers(source) {
  const results = new Set();
  const fromPattern = /\bfrom\s*['"]([^'"]+)['"]/g;
  const sideEffectPattern = /\bimport\s*['"]([^'"]+)['"]/g;
  for (const pattern of [fromPattern, sideEffectPattern]) {
    let match;
    while ((match = pattern.exec(source))) {
      if (match[1].startsWith('.')) results.add(match[1]);
    }
  }
  return [...results];
}

async function resolveModule(fromFile, specifier) {
  const base = resolve(dirname(fromFile), specifier);
  const candidates = extname(base) ? [base] : [base, `${base}.js`, join(base, 'index.js')];
  for (const candidate of candidates) {
    try {
      if ((await stat(candidate)).isFile()) return candidate;
    } catch {}
  }
  throw new Error(`Cannot resolve ${specifier} from ${relative(sourceRoot, fromFile)}`);
}

async function collectRuntimeModules(entry = resolve(sourceRoot, 'game.js')) {
  const pending = [entry];
  const visited = new Set();
  while (pending.length) {
    const file = pending.pop();
    if (visited.has(file)) continue;
    const rel = relative(sourceRoot, file);
    if (rel.startsWith(`..${sep}`) || rel === '..') throw new Error(`Runtime import escapes source root: ${file}`);
    visited.add(file);
    const source = await readFile(file, 'utf8');
    for (const specifier of relativeImportSpecifiers(source)) {
      pending.push(await resolveModule(file, specifier));
    }
  }
  return [...visited].sort();
}

async function writeRuntimeModules(outputRoot) {
  const modules = await collectRuntimeModules();
  for (const sourceFile of modules) {
    const rel = relative(sourceRoot, sourceFile);
    const outputFile = resolve(outputRoot, rel);
    await mkdir(dirname(outputFile), { recursive: true });
    if (rel === 'src/wechat/BuildProfile.js') {
      await writeFile(outputFile, RELEASE_PROFILE_SOURCE);
      continue;
    }
    let source = await readFile(sourceFile, 'utf8');
    if (rel === 'src/vfx/VfxTestConfig.js') {
      source = source.replace('export const VFX_TEST_MODE = true;', 'export const VFX_TEST_MODE = false;');
      if (source.includes('export const VFX_TEST_MODE = true;')) {
        throw new Error('Failed to disable VFX_TEST_MODE in staged release');
      }
    }
    await writeFile(outputFile, source);
  }
  return modules.map(file => relative(sourceRoot, file));
}

async function writeAudioPackages(outputRoot) {
  for (const [packageName, files] of Object.entries(AUDIO_LAYOUT)) {
    const packageRoot = resolve(outputRoot, 'packages', packageName);
    await mkdir(packageRoot, { recursive: true });
    await writeFile(join(packageRoot, 'game.js'), "// Audio-only ordinary subpackage entry.\nmodule.exports = {};\n");
    for (const audioRel of files) {
      const sourceFile = resolve(sourceRoot, 'assets/audio', audioRel);
      const outputFile = resolve(packageRoot, audioRel);
      await mkdir(dirname(outputFile), { recursive: true });
      await copyFile(sourceFile, outputFile);
    }
  }
}

async function walkFiles(root, current = root) {
  const output = [];
  for (const entry of await readdir(current, { withFileTypes: true })) {
    const fullPath = resolve(current, entry.name);
    if (entry.isDirectory()) output.push(...await walkFiles(root, fullPath));
    else if (entry.isFile()) output.push(fullPath);
  }
  return output.sort();
}

async function sha256(file) {
  return createHash('sha256').update(await readFile(file)).digest('hex');
}

function packageNameFor(relativePath) {
  for (const name of Object.keys(AUDIO_LAYOUT)) {
    if (relativePath === `packages/${name}` || relativePath.startsWith(`packages/${name}/`)) return name;
  }
  return 'main';
}

export async function inspectRelease(outputRoot = defaultOutput) {
  const resolvedOutput = resolve(outputRoot);
  assertSafeOutput(resolvedOutput);
  const allFiles = await walkFiles(resolvedOutput);
  const files = [];
  const packageBytes = { main: 0, 'audio-menu': 0, 'audio-battle': 0 };
  for (const file of allFiles) {
    const rel = relative(resolvedOutput, file).split(sep).join('/');
    const bytes = (await stat(file)).size;
    const packageName = packageNameFor(rel);
    packageBytes[packageName] += bytes;
    files.push({ path: rel, package: packageName, bytes, sha256: await sha256(file) });
  }
  const totalBytes = Object.values(packageBytes).reduce((sum, bytes) => sum + bytes, 0);
  return {
    outputRoot: resolvedOutput,
    files,
    packageBytes,
    totalBytes,
    limits: RELEASE_LIMITS,
    mainHeadroomBytes: RELEASE_LIMITS.mainPackageBytes - packageBytes.main,
    totalHeadroomBytes: RELEASE_LIMITS.totalPackageBytes - totalBytes,
  };
}

export async function verifyRelease(outputRoot = defaultOutput) {
  const inspection = await inspectRelease(outputRoot);
  const errors = [];
  if (inspection.packageBytes.main > RELEASE_LIMITS.mainPackageBytes) errors.push('Main package exceeds 4 MiB');
  if (inspection.totalBytes > RELEASE_LIMITS.totalPackageBytes) errors.push('Total package exceeds 20 MiB');

  const gameConfig = JSON.parse(await readFile(resolve(outputRoot, 'game.json'), 'utf8'));
  const packageNames = new Set((gameConfig.subpackages || []).map(entry => entry.name));
  for (const required of Object.keys(AUDIO_LAYOUT)) {
    if (!packageNames.has(required)) errors.push(`game.json is missing subpackage ${required}`);
  }

  const stagedVfxConfig = await readFile(resolve(outputRoot, 'src/vfx/VfxTestConfig.js'), 'utf8');
  if (!stagedVfxConfig.includes('export const VFX_TEST_MODE = false;')) errors.push('VFX test mode is not disabled');
  const stagedBuildProfile = await readFile(resolve(outputRoot, 'src/wechat/BuildProfile.js'), 'utf8');
  if (!stagedBuildProfile.includes("name: 'release'") || !stagedBuildProfile.includes('release: true')) {
    errors.push('Release build profile was not staged');
  }

  const forbidden = inspection.files.filter(file => (
    file.path.startsWith('tests/')
    || file.path.startsWith('vfx-review/')
    || file.path.endsWith('.html')
    || file.path.endsWith('.map')
  ));
  if (forbidden.length) errors.push(`Forbidden development files: ${forbidden.map(file => file.path).join(', ')}`);
  if (errors.length) throw new Error(errors.join('\n'));
  return inspection;
}

export async function buildRelease({ outputRoot = defaultOutput, version = '0.1.0' } = {}) {
  const resolvedOutput = resolve(outputRoot);
  assertSafeOutput(resolvedOutput);
  await rm(resolvedOutput, { recursive: true, force: true });
  await mkdir(resolvedOutput, { recursive: true });

  const runtimeModules = await writeRuntimeModules(resolvedOutput);
  await writeAudioPackages(resolvedOutput);
  await writeFile(resolve(resolvedOutput, 'game.json'), `${JSON.stringify({
    deviceOrientation: 'portrait',
    showStatusBar: false,
    subpackages: [
      { name: 'audio-menu', root: 'packages/audio-menu' },
      { name: 'audio-battle', root: 'packages/audio-battle' },
    ],
  }, null, 2)}\n`);
  await writeFile(resolve(resolvedOutput, 'project.config.json'), `${JSON.stringify({
    description: 'Combo Checkers WeChat release baseline',
    compileType: 'game',
    projectname: 'combo-checkers',
    setting: {
      es6: true,
      minified: true,
      uploadWithSourceMap: false,
      compileHotReLoad: false,
      checkInvalidKey: true,
      useCompilerModule: true,
    },
  }, null, 2)}\n`);

  const inspection = await verifyRelease(resolvedOutput);
  const manifest = {
    format: 1,
    version,
    profile: 'wechat-release-baseline',
    createdAt: new Date().toISOString(),
    sourceRoot,
    runtimeModules,
    packageBytes: inspection.packageBytes,
    totalBytes: inspection.totalBytes,
    limits: inspection.limits,
    mainHeadroomBytes: inspection.mainHeadroomBytes,
    totalHeadroomBytes: inspection.totalHeadroomBytes,
    files: inspection.files,
  };
  const manifestPath = manifestPathFor(resolvedOutput);
  await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  return { ...inspection, manifest, manifestPath };
}

function parseArguments(argv) {
  const options = {};
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--out') options.outputRoot = resolve(argv[++index]);
    else if (argv[index] === '--version') options.version = argv[++index];
    else throw new Error(`Unknown argument: ${argv[index]}`);
  }
  return options;
}

if (process.argv[1] && basename(process.argv[1]) === 'build-wechat-release.mjs') {
  buildRelease(parseArguments(process.argv.slice(2))).then(result => {
    console.log(JSON.stringify({
      outputRoot: result.outputRoot,
      manifestPath: result.manifestPath,
      version: result.manifest.version,
      packageBytes: result.packageBytes,
      totalBytes: result.totalBytes,
      mainHeadroomBytes: result.mainHeadroomBytes,
      totalHeadroomBytes: result.totalHeadroomBytes,
    }, null, 2));
  }).catch(error => {
    console.error(error);
    process.exitCode = 1;
  });
}
